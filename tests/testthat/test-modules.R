row_of <- function(df, id, yr) df[df$unitid == id & df$year == yr, , drop = FALSE]

test_that("directory is harmonized across locale and Carnegie changes", {
	local_fake_ipeds()
	d <- ipeds_directory(c(2005, 2007, 2009, 2010, 2021), quiet = TRUE)
	expect_equal(nrow(d), 20)
	r05 <- d[d$year == 2005, ]
	expect_equal(as.character(r05$locale4), c("City", "Suburb", "Town", "Rural"))
	expect_equal(as.character(r05$carnegie_group), c("Doctoral", "Baccalaureate", "Associate's", "Special focus"))
	expect_equal(unique(r05$carnegie_edition), "2000")
	r21 <- d[d$year == 2021, ]
	expect_equal(as.character(r21$locale4), c("City", "Suburb", "Town", "Rural"))
	expect_equal(r21$carnegie_basic, c(15, 21, 2, 10))
	expect_equal(unique(r21$carnegie_edition), "2021")
	expect_equal(as.character(r21$carnegie_group), c("Doctoral", "Baccalaureate", "Associate's", "Associate's"))
	expect_equal(as.character(r21$sector)[1:2], c("Public, 4-year or above", "Private nonprofit, 4-year or above"))
	expect_equal(r21$hbcu, c(FALSE, TRUE, FALSE, FALSE))
	expect_equal(r21$zip5, c("01234", "02138", "01234", "75001"))
	expect_equal(row_of(d, 100001, 2009)$instnm, "Alpha State University (revised)")
	expect_equal(row_of(d, 100004, 2010)$instnm, "Universidad Polit\u00e9cnica Gamma")
	expect_equal(attr(d$locale4, "label"), "Locale: city, suburb, town or rural (harmonized)")
	a <- ipeds_audit(d)
	expect_true(all(a$status[a$year == 2007 & a$concept == "sector"] == "unverified"))
	expect_true(all(a$status[a$year == 2010 & a$concept == "sector"] == "verified"))
})

test_that("fall enrollment is harmonized across race schemes and level codes", {
	local_fake_ipeds()
	e <- ipeds_enrollment(c(2007, 2009, 2010, 2013), quiet = TRUE)
	expect_equal(nrow(e), 8)
	for (yr in c(2007, 2009, 2010, 2013)) {
		r <- row_of(e, 100001, yr)
		expect_equal(r$enr_total, 5000, ignore_attr = TRUE)
		expect_equal(r$enr_ug, 4000, ignore_attr = TRUE)
		expect_equal(r$enr_grad, 1000, ignore_attr = TRUE)
		expect_equal(r$enr_ft + r$enr_pt, 5000, ignore_attr = TRUE)
		expect_equal(r$enr_ug_ft, 3000, ignore_attr = TRUE)
		expect_equal(r$enr_grad_pt, 500, ignore_attr = TRUE)
		expect_equal(r$enr_ug_firsttime, 1000, ignore_attr = TRUE)
		expect_equal(r$enr_ug_ft_firsttime, 500, ignore_attr = TRUE)
		expect_equal(r$enr_men, 2000, ignore_attr = TRUE)
		expect_equal(r$enr_asian_pi, 500, ignore_attr = TRUE)
		expect_equal(r$enr_ug_asian_pi, 400, ignore_attr = TRUE)
	}
	expect_equal(row_of(e, 100001, 2007)$enr_white, 2700)
	expect_true(is.na(row_of(e, 100001, 2007)$enr_two_more))
	expect_equal(row_of(e, 100001, 2009)$enr_two_more, 200)
	expect_true(is.na(row_of(e, 100002, 2009)$enr_two_more))
	expect_equal(row_of(e, 100002, 2009)$enr_race_scheme, "7 categories (1977 standards)")
	expect_equal(row_of(e, 100002, 2010)$enr_race_scheme, "9 categories (1997 standards)")
	expect_equal(row_of(e, 100002, 2013)$enr_ug_ft_firsttime, 1000)
	a <- ipeds_audit(e)
	relab <- a[a$status == "relabeled", ]
	expect_equal(nrow(relab), 1)
	expect_equal(relab$year, 2013L)
	expect_equal(relab$source, "efalevel = 25")
	expect_equal(nrow(ipeds_audit(e, problems_only = TRUE)), 0)
})

test_that("enrollment identity checks blank implausible values", {
	local_fake_ipeds()
	ctx <- list(audit = ipeds:::.audit_new(), module = "t", year = 1L)
	res <- data.frame(enr_total = c(10, 10, 10), enr_ft = c(1, 1, 1), enr_pt = c(1, 1, 1))
	out <- ipeds:::.identity_check(res, abs(res$enr_ft + res$enr_pt - res$enr_total) <= 1,
								   c("enr_ft", "enr_pt"), ctx, "ft + pt = total")
	expect_true(all(is.na(out$enr_ft)))
	expect_equal(ipeds:::.audit_table(ctx$audit)$status, "check_failed")
})

