test_that("completions are harmonized across award level changes", {
	local_fake_ipeds()
	cc <- ipeds_completions(c(2008, 2013, 2021), quiet = TRUE)
	r08 <- row_of(cc, 100001, 2008)
	expect_equal(r08$awards_total, 900)
	expect_equal(r08$awards_bach, 150)
	expect_equal(r08$awards_doctor_pre2010, 150)
	expect_equal(r08$awards_first_prof, 150)
	expect_equal(r08$awards_postmaster_cert, 150)
	expect_equal(r08$awards_doctor, 300)
	expect_true(is.na(r08$awards_doctor_research))
	expect_equal(r08$bach_white, 81)
	expect_true(is.na(r08$bach_asian))
	expect_equal(r08$bach_asian_pi, 15)
	r13 <- row_of(cc, 100001, 2013)
	expect_equal(r13$awards_doctor, 450)
	expect_equal(r13$awards_cert_lt1, 150)
	expect_true(is.na(r13$awards_first_prof))
	expect_equal(r13$bach_asian, 12)
	expect_equal(r13$bach_asian_pi, 15)
	r21 <- row_of(cc, 100001, 2021)
	expect_equal(r21$awards_cert_lt1, 300)
	expect_equal(r21$awards_total, 1350)
	expect_equal(r21$awards_doctor, 300)
	expect_equal(row_of(cc, 100002, 2021)$awards_master, 0)
	expect_equal(row_of(cc, 100002, 2021)$awards_bach, 200)
	a <- ipeds_audit(cc)
	expect_match(a$detail[a$year == 2021 & a$concept == "award levels"], "unmapped codes .*12")
	expect_match(a$detail[a$year == 2021 & a$concept == "institution totals"], "used for 2 institutions")
	expect_true(any(a$concept == "grand total = sum of programs" & grepl("100.0%", a$detail)))
})

