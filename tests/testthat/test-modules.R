	expect_equal(b$cip, c("01", "27"))
	expect_equal(b$awards, c(50, 100))
	expect_equal(unique(p$cip_edition), "2010")
	p6 <- ipeds_completions_programs(2021, quiet = TRUE, by_race = TRUE)
	expect_true("awlevel_12" %in% p6$award_level)
	expect_true(all(c("awards_white", "awards_asian_pi") %in% names(p6)))
	expect_equal(attr(p6$awards_women, "label"), "Awards conferred (first majors): Women")
	expect_equal(attr(p6$cip, "label"), "CIP code of the program")
	expect_error(ipeds_completions_programs(2021, cip_digits = 3), "must be 2, 4 or 6")
})

test_that("admissions bridge IC and ADM and harmonize test policy", {
	local_fake_ipeds()
	a <- ipeds_admissions(2013:2014, quiet = TRUE)
	r13 <- row_of(a, 100001, 2013)
	expect_equal(r13$applicants, 10000)
	expect_equal(r13$admit_rate, 0.6)
	expect_equal(r13$yield_rate, 2000 / 6000)
	expect_equal(r13$sat_math_25, 510)
	expect_equal(r13$sat_version, "Pre-2016 SAT")
	expect_equal(as.character(r13$test_policy), "Required")
	expect_false(r13$open_admission)
	expect_equal(row_of(a, 100001, 2014)$applicants, 10000)
	expect_equal(as.character(row_of(a, 100002, 2013)$test_policy), "Not required or considered")
	expect_equal(as.character(row_of(a, 100002, 2014)$test_policy), "Considered but not required")
	r3 <- row_of(a, 100003, 2013)
	expect_true(r3$open_admission)
	expect_true(is.na(r3$sat_version))
	aud <- ipeds_audit(a)
	expect_equal(aud$status[aud$year == 2014 & aud$concept == "applicants" & aud$status != "not_found"], "derived")
})

